def test_disable_blocks_new_requests_not_already_admitted_transaction(setup, monkeypatch):
    client, _, settings, job_id, payload, _ = setup
    entered = threading.Event()
    release = threading.Event()
    checksum = review.generated_checksum

    def pause(job):
        entered.set()
        assert release.wait(timeout=10)
        return checksum(job)

    monkeypatch.setattr(review, "generated_checksum", pause)
    with ThreadPoolExecutor(max_workers=1) as pool:
        admitted = pool.submit(post, client, job_id, payload)
        try:
            assert entered.wait(timeout=10)
            settings.review_workflow_enabled = False
            assert post(client, job_id, payload).status_code == 503
        finally:
            release.set()
        result = admitted.result(timeout=10)
    assert result.status_code == 200
    assert result.json()["status"] == "approved"
    assert result.json()["review_enabled"] is False
    assert len(client.get(f"/v1/jobs/{job_id}/reviews", headers=headers()).json()) == 1


def test_racing_independent_sessions_atomic_cas(setup, monkeypatch):
    _, sessions, _, job_id, payload, _ = setup
    barrier = threading.Barrier(2)
    checksum = review.generated_checksum

    def synchronized(job):
        value = checksum(job)
        barrier.wait(timeout=10)
        return value

    monkeypatch.setattr(review, "generated_checksum", synchronized)

    def race(decision):
        with sessions() as db:
            job = db.get(Job, job_id)
            try:
                review.decide(db, job, Actor(name="openwebui", roles=["reviewer"]),
                              review.ReviewDecision.model_validate(payload | {"decision": decision}))
                return 200
            except HTTPException as exc:
                return exc.status_code

    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(race, ["approved", "rejected"]))
    assert sorted(results) == [200, 409]
    with sessions() as db:
        evidence = db.scalars(select(Review)).all()
        assert len(evidence) == 1
        assert db.get(Job, job_id).status == evidence[0].decision
        assert db.get(Job, job_id).review_version == evidence[0].version == 1
        assert db.scalar(select(func.count()).select_from(Audit)) == 1


