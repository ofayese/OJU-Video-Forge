def test_migration_old_rows_and_non_destructive_downgrade(tmp_path):
    url = f"sqlite:///{tmp_path}/old.db"
    env = os.environ | {"DATABASE_URL": url, "APP_ENV": "test"}

    def migrate(*args):
        return subprocess.run([sys.executable, "-m", "alembic", "-c", str(ROOT / "alembic.ini"), *args],
                              cwd=ROOT, env=env, capture_output=True, text=True)

    result = migrate("upgrade", "0001")
    assert result.returncode == 0, result.stderr
    engine = create_engine(url)
    with engine.begin() as db:
        db.execute(text("INSERT INTO jobs (id,owner,operation,status,spec,artifact,created_at,updated_at) "
                        "VALUES ('old','openwebui','render_test','awaiting_review','{}','old/test.mp4',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)"))
        db.execute(text("INSERT INTO audit_events (job_id,actor,action,at) VALUES ('old','worker','awaiting_review',CURRENT_TIMESTAMP)"))
    result = migrate("upgrade", "head")
    assert result.returncode == 0, result.stderr
    with engine.begin() as db:
        row = db.execute(text("SELECT status,artifact,review_version,artifact_id,artifact_sha256 FROM jobs")).one()
        assert tuple(row) == ("awaiting_review", "old/test.mp4", 0, None, None)
        assert db.scalar(text("SELECT count(*) FROM audit_events")) == 1
        db.execute(text("INSERT INTO job_reviews (job_id,actor,at,artifact_id,artifact_sha256,expected_version,version,decision) "
                        "VALUES ('old','openwebui',CURRENT_TIMESTAMP,'opaque',:digest,0,1,'approved')"), {"digest": "a" * 64})
    result = migrate("downgrade", "base")
    assert result.returncode != 0
    assert "disable REVIEW_WORKFLOW_ENABLED" in result.stderr
    with engine.connect() as db:
        assert db.scalar(text("SELECT count(*) FROM job_reviews")) == 1
        assert db.scalar(text("SELECT count(*) FROM audit_events")) == 1
        assert db.scalar(text("SELECT version_num FROM alembic_version")) == "0007"
        with pytest.raises(DBAPIError, match="immutable"):
            db.execute(text("DELETE FROM job_reviews"))
    engine.dispose()


