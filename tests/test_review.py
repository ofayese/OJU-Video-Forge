    if mismatch == "version":
        payload["expected_version"] = 1
    elif mismatch in ("id", "checksum"):
        payload["expected_artifact"]["id" if mismatch == "id" else "sha256"] = "b" * (1 if mismatch == "id" else 64)
    elif mismatch == "actual":
        artifact.write_bytes(b"changed")
    elif mismatch == "empty":
        artifact.write_bytes(b"")
