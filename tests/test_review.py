@pytest.mark.parametrize("decision", ["approved", "rejected"])
def test_decision_and_immutable_history(setup, decision):
    client, sessions, _, job_id, payload, _ = setup
    response = client.get(f"/v1/jobs/{job_id}", headers=headers())
    assert response.status_code == 200
    assert response.json()["can_review"] is True
    assert response.json()["review_artifact"] == payload["expected_artifact"]
    assert client.get(f"/v1/jobs/{job_id}/reviews", headers=headers()).json() == []
    payload["decision"] = decision
    result = post(client, job_id, payload)
    assert result.status_code == 200
    assert result.json()["status"] == decision
    assert result.json()["review_version"] == 1
    assert result.json()["can_review"] is False
    history = client.get(f"/v1/jobs/{job_id}/reviews", headers=headers()).json()
    assert len(history) == 1
    assert history[0].items() >= {
        "job_id": job_id, "actor": "openwebui", "decision": decision,
        "artifact_id": payload["expected_artifact"]["id"],
        "artifact_sha256": payload["expected_artifact"]["sha256"],
        "expected_version": 0, "version": 1, "contract_version": 1,
    }.items()
    assert history[0]["at"]
    assert "private-not-in-evidence" not in str(history)
    assert "test.mp4" not in str(history)
    for repeated in ("approved", "rejected"):
        payload["decision"] = repeated
        payload["expected_version"] = 1
        assert post(client, job_id, payload).status_code == 409
    with sessions() as db:
        assert db.scalar(select(func.count()).select_from(Review)) == 1
        assert db.scalar(select(func.count()).select_from(Audit)) == 1
        for sql in ("UPDATE job_reviews SET actor='changed'", "DELETE FROM job_reviews"):
            with pytest.raises(DBAPIError, match="immutable"):
                db.execute(text(sql))
            db.rollback()
        original = db.scalar(select(Review))
        replacements = (
            {
                "id": original.id,
                "job_id": job_id,
                "actor": "replacement",
                "at": original.at,
                "artifact_id": original.artifact_id,
                "artifact_sha256": original.artifact_sha256,
                "expected_version": original.version,
                "version": original.version + 1,
                "decision": "rejected",
            },
            {
                "id": original.id + 1,
                "job_id": job_id,
                "actor": "replacement",
                "at": original.at,
                "artifact_id": original.artifact_id,
                "artifact_sha256": original.artifact_sha256,
                "expected_version": original.expected_version,
                "version": original.version,
                "decision": "rejected",
            },
        )
        for replacement in replacements:
            with pytest.raises(DBAPIError, match="immutable"):
                db.execute(
                    text(
                        "INSERT OR REPLACE INTO job_reviews "
                        "(id,job_id,actor,at,artifact_id,artifact_sha256,expected_version,version,decision) "
                        "VALUES (:id,:job_id,:actor,:at,:artifact_id,:artifact_sha256,"
                        ":expected_version,:version,:decision)"
                    ),
                    replacement,
                )
            db.rollback()
            assert tuple(db.execute(text(
                "SELECT id,actor,expected_version,version,decision FROM job_reviews"
            )).one()) == (
                original.id, original.actor, original.expected_version, original.version, decision,
            )
    # Repeat worker deliveries cannot overwrite terminal decisions.
    worker.execute(job_id)
    with sessions() as db:
        assert db.get(Job, job_id).status == decision
        assert db.scalar(select(func.count()).select_from(Review)) == 1


